BY_NAME: dict[str, str] = {k.lower(): v for k, v in _BY_NAME_RAW.items()}


def name_has_cjk(text: str | None) -> bool:
    """True when the string already contains Chinese characters."""
    if not text:
        return False
    return any("\u4e00" <= ch <= "\u9fff" for ch in str(text))


def persist_auto_names(updates: dict[int, str]) -> int:
    """Merge auto translations into memory + ``data/team_names_auto.json``.

    Curated ``BY_ID`` entries are never overwritten here. Returns how many ids
    were newly stored or changed in the auto map.
    """
    if not updates:
        return 0
    changed = 0
    for tid, zh in updates.items():
        text = str(zh or "").strip()
        if tid <= 0 or not text or tid in BY_ID:
            continue
        if AUTO_BY_ID.get(tid) == text:
            continue
        AUTO_BY_ID[tid] = text
        changed += 1
    if not changed:
        return 0
    _DATA_DIR.mkdir(parents=True, exist_ok=True)
    payload = {str(k): v for k, v in sorted(AUTO_BY_ID.items())}
    AUTO_NAMES_PATH.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    return changed


def team_name_zh(name: str | None, team_id: int | None = None) -> str:
    """Resolve Chinese display name; fall back to original / empty."""
    if team_id is not None:
        try:
            tid = int(team_id)
        except (TypeError, ValueError):
            tid = None
        if tid is not None and tid in BY_ID:
            return BY_ID[tid]
        if tid is not None and tid in AUTO_BY_ID:
            return AUTO_BY_ID[tid]
    if not name:
        return ""
    trimmed = str(name).strip()
    hit = BY_NAME.get(trimmed.lower())
    if hit:
        return hit
    return trimmed


def team_needs_zh(name: str | None, team_id: int | None = None) -> bool:
    """True when resolved display name still has no Chinese characters."""
    return not name_has_cjk(team_name_zh(name, team_id))


def localize_match_teams(match: dict[str, Any]) -> dict[str, Any]:
    """Rewrite home/away labels on a form/H2H match row (in place + return)."""
    home_id = match.get("home_id")
    away_id = match.get("away_id")
    try:
        hid = int(home_id) if home_id is not None else None
    except (TypeError, ValueError):
        hid = None
    try:
        aid = int(away_id) if away_id is not None else None
    except (TypeError, ValueError):
        aid = None
    home = match.get("home")
    away = match.get("away")
    if home is not None or hid is not None:
        match["home"] = team_name_zh(home if isinstance(home, str) else None, hid) or home
    if away is not None or aid is not None:
        match["away"] = team_name_zh(away if isinstance(away, str) else None, aid) or away
    return match


async def backfill_team_names(session: Any) -> int:
    """Rewrite ``teams.name`` for every row that has a Chinese mapping.

    Returns the number of rows changed. Call after fixture sync so historical
    English rows become reusable Chinese names without waiting for re-fetch.
    """
    from sqlalchemy import select

    from app.models.team import Team

    rows = (await session.execute(select(Team))).scalars().all()
    updated = 0
    for team in rows:
        zh = team_name_zh(team.name, team.id)
        if zh and zh != team.name:
            team.name = zh
            updated += 1
