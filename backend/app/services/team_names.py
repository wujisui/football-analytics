"""API-Sports team id / English name → 中文 display name.

Single source of truth for club/national-team display names:
- applied on ingest (``FootballFetcher._upsert_team``)
- backfilled across ``teams`` after sync
- applied when summarizing / serving H2H & form packages

Naming style: short English keys / common IDs use fan-facing short Chinese
(e.g. Bayern→拜仁, PSG→巴黎); fuller official English keeps fuller Chinese
(e.g. Bayern Munich→拜仁慕尼黑). Multiple keys for one club are intentional aliases.

``BY_ID`` / ``_BY_NAME_RAW`` are grouped by competition (五大联赛 → 二级联赛 →
亚欧美 → 欧陆其他), with ids sorted inside each group. Prefer adding new
entries under the matching league comment — not under date-based dumps.

Unmapped names stay as the official string.
"""

from __future__ import annotations

